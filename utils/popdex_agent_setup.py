def get_network(network: Optional[str]) -> Dict[str, Any]:
    value = str(network or os.getenv("POPDEX_NETWORK") or "mainnet").strip().lower()
    if value in {"test", "testnet"}:
        value = "testnet"
    elif value in {"main", "mainnet"}:
        value = "mainnet"
    else:
        raise ValueError("POPDEX network must be mainnet or testnet")
    return dict(NETWORKS[value])


def derive_agent_address(private_key: Optional[str] = None) -> Optional[str]:
    key = str(private_key or os.getenv("POPDEX_AGENT_PRIVATE_KEY") or "").strip()
    if not key:
        return None
    try:
        return Account.from_key(key).address
    except Exception:
        return None


def _write_env_values(values: Dict[str, Any]) -> None:
    """Update selected .env entries atomically without exposing secret values."""
    normalized = {key: str(value) for key, value in values.items()}
    with _ENV_LOCK:
        existing_lines = []
        if ENV_PATH.exists():
            existing_lines = ENV_PATH.read_text(encoding="utf-8").splitlines()

        remaining = dict(normalized)
        output_lines = []
        for line in existing_lines:
            stripped = line.strip()
            if stripped and not stripped.startswith("#") and "=" in line:
                key = line.split("=", 1)[0].strip()
                if key in remaining:
                    output_lines.append(f"{key}={remaining.pop(key)}")
                    continue
            output_lines.append(line)

        if remaining:
            if output_lines and output_lines[-1].strip():
                output_lines.append("")
            if not existing_lines:
                output_lines.append("# POPDEX Agent setup (generated by local Web dashboard)")
            for key, value in remaining.items():
                output_lines.append(f"{key}={value}")

        ENV_PATH.parent.mkdir(parents=True, exist_ok=True)
        temp_path = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="w",
                encoding="utf-8",
                newline="\n",
                dir=str(ENV_PATH.parent),
                prefix=".env.popdex-",
                suffix=".tmp",
                delete=False,
            ) as handle:
                temp_path = Path(handle.name)
                handle.write("\n".join(output_lines).rstrip() + "\n")
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temp_path, ENV_PATH)
        finally:
            if temp_path and temp_path.exists():
                temp_path.unlink(missing_ok=True)

        for key, value in normalized.items():
            os.environ[key] = value


def _rpc(network_config: Dict[str, Any], method: str, params: list) -> Dict[str, Any]:
    try:
        response = requests.post(
            network_config["rpc_url"],
            json={"jsonrpc": "2.0", "id": 1, "method": method, "params": params},
            headers={"Content-Type": "application/json"},
            timeout=10,
        )
        payload = response.json()
    except (requests.RequestException, ValueError) as exc:
        return {"error": f"POPDEX RPC request failed: {exc}"}
    if not response.ok:
        return {"error": f"POPDEX RPC returned HTTP {response.status_code}"}
    if payload.get("error") is not None:
        error = payload["error"]
        return {"error": error.get("message") if isinstance(error, dict) else str(error)}
    return payload


def get_agent_account_info(agent_address: str, network: Optional[str] = None) -> Dict[str, Any]:
    network_config = get_network(network)
    if not is_address(agent_address):
        raise ValueError("Invalid POPDEX Agent address")
    agent = to_checksum_address(agent_address)
    call_data = keccak(text=GET_ACCOUNT_INFO_SIGNATURE)[:4] + abi_encode(["address"], [agent])
    raw = _rpc(
        network_config,
        "eth_call",
        [{"to": ACCOUNT_CONTRACT, "data": "0x" + call_data.hex()}, "latest"],
    )
    if raw.get("error"):
        return {"available": False, "error": str(raw["error"])}
    result = raw.get("result")
    if not isinstance(result, str) or result in {"", "0x"}:
        return {"available": False, "error": "POPDEX returned an empty agent status"}
    try:
        decoded = abi_decode(GET_ACCOUNT_INFO_TYPES, bytes.fromhex(result.removeprefix("0x")))
    except Exception as exc:
        return {"available": False, "error": f"Unable to decode agent status: {exc}"}
    return {
        "available": True,
        "exists": bool(decoded[0]),
        "account_type": int(decoded[1]),
        "nonce": int(decoded[2]),
        "subaccount_count": int(decoded[3]),
        "delegator": to_checksum_address(decoded[4]),
        "expires_at": int(decoded[5]),
        "is_expired": bool(decoded[6]),
        "main": to_checksum_address(decoded[7]),
    }


def get_agent_setup_status(network: Optional[str] = None) -> Dict[str, Any]:
    network_config = get_network(network)
    main_address = str(os.getenv("POPDEX_ACCOUNT_ADDRESS") or "").strip()
    raw_private_key = str(os.getenv("POPDEX_AGENT_PRIVATE_KEY") or "").strip()
    agent_address = derive_agent_address(raw_private_key)
    key_valid = bool(agent_address)
    info: Dict[str, Any] = {"available": False}
    if agent_address:
        info = get_agent_account_info(agent_address, network_config["network"])

    expected_delegator = main_address.lower() if is_address(main_address) else ""
    actual_delegator = str(info.get("delegator") or "").lower()
    authorized = bool(
        info.get("available")
        and info.get("exists")
        and info.get("account_type") == 1
        and not info.get("is_expired")
        and expected_delegator
        and actual_delegator == expected_delegator
    )
    return {
        "success": True,
        "configured": bool(main_address and raw_private_key),
        "key_valid": key_valid,
        "authorized": authorized,
        "account_address": main_address or None,
        "agent_address": agent_address,
        "network": network_config["network"],
        "chain_id": network_config["chain_id"],
        "account_contract": ACCOUNT_CONTRACT,
        "agent_info": info,
    }


def prepare_agent_setup(
    main_address: str,
    network: Optional[str] = None,
    expires_in_days: int = 90,
    global_scope: bool = False,
) -> Dict[str, Any]:
    """Create/reuse a local Agent Key and build an unsigned approveAgent call."""
    if not is_address(main_address):
        raise ValueError("連接的 EVM 錢包地址無效")
    main_address = to_checksum_address(main_address)
    network_config = get_network(network)
    try:
        expires_in_days = int(expires_in_days)
    except (TypeError, ValueError):
        raise ValueError("Agent 有效天數必須是整數")
    if expires_in_days < 0 or expires_in_days > 3650:
        raise ValueError("Agent 有效天數必須介於 0 到 3650 天")

    configured_key = str(os.getenv("POPDEX_AGENT_PRIVATE_KEY") or "").strip()
    agent_address = derive_agent_address(configured_key)
    generated = False
    if not agent_address:
        agent_account = Account.create(secrets.token_bytes(32))
        configured_key = "0x" + agent_account.key.hex().removeprefix("0x")
        agent_address = agent_account.address
        generated = True

    existing_info = get_agent_account_info(agent_address, network_config["network"])
    if not existing_info.get("available"):
        raise ValueError(
            "目前無法透過 POPDEX RPC 確認 Agent 狀態；為避免重複授權，請稍後再試"
        )
    if existing_info.get("exists"):
        current_delegator = str(existing_info.get("delegator") or "")
        if current_delegator.lower() != main_address.lower():
            raise ValueError(
                "目前 Agent 已授權給另一個帳戶；請先撤銷或輪換 Agent，不會自動覆寫私鑰"
            )
        if existing_info.get("account_type") != 1:
            raise ValueError("目前金鑰地址已是其他 POPDEX 帳戶類型，無法作為 Agent")
        if existing_info.get("is_expired"):
            raise ValueError(
                "目前 Agent 已過期；POPDEX 不應以 approveAgent 重複授權同一地址，"
                "請先在 POPDEX 輪換成全新的 Agent Key"
            )
        _save_agent_environment(main_address, configured_key, network_config)
        return {
            "success": True,
            "generated": generated,
            "already_authorized": True,
            "account_address": main_address,
            "agent_address": agent_address,
            "network": network_config["network"],
            "chain_id": network_config["chain_id"],
            "agent_info": existing_info,
        }

    now_ms = int(time.time() * 1000)
    expires_at = 0 if expires_in_days == 0 else now_ms + expires_in_days * 86_400_000
    agent_name_text = f"BackpackMM-{agent_address[-8:]}"
    agent_name = agent_name_text.encode("utf-8")[:32].ljust(32, b"\0")
    call_data = keccak(text=APPROVE_AGENT_SIGNATURE)[:4] + abi_encode(
        ["address", "address", "bytes32", "uint64", "uint64", "bool"],
        [agent_address, main_address, agent_name, expires_at, now_ms, bool(global_scope)],
    )

    _save_agent_environment(main_address, configured_key, network_config)
    return {
        "success": True,
        "generated": generated,
        "already_authorized": False,
        "account_address": main_address,
        "agent_address": agent_address,
        "agent_name": agent_name_text,
        "network": network_config["network"],
        "chain_id": network_config["chain_id"],
        "chain": {
            "chainId": hex(network_config["chain_id"]),
            "chainName": network_config["chain_name"],
            "nativeCurrency": network_config["native_currency"],
            "rpcUrls": [network_config["rpc_url"]],
        },
        "transaction": {
            "to": ACCOUNT_CONTRACT,
            "data": "0x" + call_data.hex(),
            "gas": hex(1_000_000),
            "gasPrice": "0x0",
        },
        "expires_at": expires_at,
        "global_scope": bool(global_scope),
    }


def prepare_agent_management(
    action: str,
    main_address: str,
    network: Optional[str] = None,
    expires_in_days: int = 90,
) -> Dict[str, Any]:
    """Back up the current Agent, then build an unsigned revoke/replace call."""
    normalized_action = str(action or "").strip().lower()
    if normalized_action not in {"revoke", "replace"}:
        raise ValueError("Agent 管理動作必須是 revoke 或 replace")

    with _MANAGEMENT_LOCK:
        context = _get_managed_agent_context(main_address, network)
        network_config = context["network_config"]
        old_agent = context["agent_address"]
        backup_file = _backup_agent_environment(normalized_action, old_agent)
        operation_id = secrets.token_hex(16)
        pending: Dict[str, Any] = {
            "operation_id": operation_id,
            "action": normalized_action,
            "created_at": int(time.time() * 1000),
            "backup_file": backup_file,
            "account_address": context["main_address"],
            "old_agent_address": old_agent,
            "network": network_config["network"],
        }

        if normalized_action == "replace":
            expires_in_days = _validate_expiry_days(expires_in_days)
            new_agent_account = Account.create(secrets.token_bytes(32))
            new_private_key = "0x" + new_agent_account.key.hex().removeprefix("0x")
            now_ms = int(time.time() * 1000)
            expires_at = (
                0
                if expires_in_days == 0
                else now_ms + expires_in_days * 86_400_000
            )
            call_data = keccak(text=REPLACE_AGENT_SIGNATURE)[:4] + abi_encode(
                ["address", "address", "uint64", "uint64"],
                [old_agent, new_agent_account.address, expires_at, now_ms],
            )
            pending.update(
                {
                    "new_agent_address": new_agent_account.address,
                    "new_private_key": new_private_key,
                    "expires_at": expires_at,
                }
            )
        else:
            call_data = keccak(text=REVOKE_AGENT_SIGNATURE)[:4] + abi_encode(
                ["address"], [old_agent]
            )

        _write_pending_operation(pending)
        result = {
            "success": True,
            "action": normalized_action,
            "operation_id": operation_id,
            "backup_file": backup_file,
            "account_address": context["main_address"],
            "old_agent_address": old_agent,
            "network": network_config["network"],
            "chain_id": network_config["chain_id"],
            "chain": _chain_payload(network_config),
            "transaction": _transaction_payload(call_data),
        }
        if normalized_action == "replace":
            result.update(
                {
                    "new_agent_address": pending["new_agent_address"],
                    "expires_at": pending["expires_at"],
                }
            )
        return result


def finalize_agent_management(operation_id: str) -> Dict[str, Any]:
    """Persist local state only after the wallet transaction is confirmed on-chain."""
    with _MANAGEMENT_LOCK:
        pending = _read_pending_operation(operation_id)
        network = pending["network"]
        action = pending["action"]
        target_agent = (
            pending["new_agent_address"]
            if action == "replace"
            else pending["old_agent_address"]
        )
        info = get_agent_account_info(target_agent, network)
        if not info.get("available"):
            raise ValueError(
                "鏈上交易已送出，但目前無法確認 Agent 狀態；請稍後重試完成作業"
            )

        if action == "replace":
            expected_delegator = str(pending["account_address"]).lower()
            if not (
                info.get("exists")
                and info.get("account_type") == 1
                and not info.get("is_expired")
                and str(info.get("delegator") or "").lower() == expected_delegator
            ):
                raise ValueError("尚未讀到新的 POPDEX Agent 鏈上授權，請稍後重試")
            _save_agent_environment(
                pending["account_address"],
                pending["new_private_key"],
                get_network(network),
            )
        else:
            if info.get("exists"):
                raise ValueError("尚未讀到 POPDEX Agent 撤銷結果，請稍後重試")
            # Keep the main account and network settings for a future fresh setup,
            # but make the revoked key impossible for the bot to keep using.
            _write_env_values({"POPDEX_AGENT_PRIVATE_KEY": ""})

        _pending_operation_path(operation_id).unlink(missing_ok=True)
        status = get_agent_setup_status(network)
        status.update(
            {
                "action": action,
                "backup_file": pending["backup_file"],
            }
        )
        return status


def abort_agent_management(operation_id: str) -> Dict[str, Any]:
    """Discard a staged new key after a rejected or reverted wallet transaction."""
    with _MANAGEMENT_LOCK:
        pending = _read_pending_operation(operation_id)
        _pending_operation_path(operation_id).unlink(missing_ok=True)
        return {
            "success": True,
            "action": pending["action"],
            "backup_file": pending["backup_file"],
        }


def _get_managed_agent_context(
    main_address: str, network: Optional[str]
) -> Dict[str, Any]:
    if not is_address(main_address):
        raise ValueError("連接的 EVM 錢包地址無效")
    main_address = to_checksum_address(main_address)
    configured_main = str(os.getenv("POPDEX_ACCOUNT_ADDRESS") or "").strip()
    private_key = str(os.getenv("POPDEX_AGENT_PRIVATE_KEY") or "").strip()
    agent_address = derive_agent_address(private_key)
    if not configured_main or not agent_address:
        raise ValueError("目前沒有可管理的 POPDEX Agent 設定")
    if not is_address(configured_main) or configured_main.lower() != main_address.lower():
        raise ValueError("請連接原本授權此 Agent 的 POPDEX 主錢包")

    network_config = get_network(network)
    configured_network = get_network(os.getenv("POPDEX_NETWORK"))["network"]
    if network_config["network"] != configured_network:
        raise ValueError("選擇的 POPDEX 網路與目前 Agent 設定不一致")

    info = get_agent_account_info(agent_address, network_config["network"])
    if not info.get("available"):
        raise ValueError("目前無法確認 POPDEX Agent 鏈上狀態，未執行管理操作")
    if not info.get("exists") or info.get("account_type") != 1:
        raise ValueError("目前 Agent 已不在鏈上授權清單，請重新檢查狀態")
    if str(info.get("delegator") or "").lower() != main_address.lower():
        raise ValueError("目前 Agent 的鏈上授權帳戶與連接錢包不一致")
    return {
        "main_address": main_address,
        "agent_address": agent_address,
        "agent_info": info,
        "network_config": network_config,
    }


def _validate_expiry_days(value: Any) -> int:
    try:
        days = int(value)
    except (TypeError, ValueError):
        raise ValueError("Agent 有效天數必須是整數")
    if days < 0 or days > 3650:
        raise ValueError("Agent 有效天數必須介於 0 到 3650 天")
    return days


def _chain_payload(network_config: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "chainId": hex(network_config["chain_id"]),
        "chainName": network_config["chain_name"],
        "nativeCurrency": network_config["native_currency"],
        "rpcUrls": [network_config["rpc_url"]],
    }


def _transaction_payload(call_data: bytes) -> Dict[str, str]:
    return {
        "to": ACCOUNT_CONTRACT,
        "data": "0x" + call_data.hex(),
        "gas": hex(1_000_000),
        "gasPrice": "0x0",
    }


def _ensure_backup_dir() -> None:
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(BACKUP_DIR, 0o700)
    except OSError:
        pass


def _backup_agent_environment(action: str, agent_address: str) -> str:
    _ensure_backup_dir()
    stamp = time.strftime("%Y%m%d-%H%M%S", time.localtime())
    backup_path = BACKUP_DIR / (
        f"popdex-agent-{action}-{stamp}-{agent_address[-6:].lower()}-"
        f"{secrets.token_hex(3)}.env"
    )
    lines = [
        "# POPDEX Agent backup created before on-chain management",
        f"# action={action}",
        f"# agent_address={agent_address}",
    ]
    for key in POPDEX_AGENT_ENV_KEYS:
        value = str(os.getenv(key) or "").replace("\r", "").replace("\n", "")
        lines.append(f"{key}={value}")
    with backup_path.open("x", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
        handle.flush()
        os.fsync(handle.fileno())
    try:
        os.chmod(backup_path, 0o600)
    except OSError:
        pass
    return _display_path(backup_path)


def _pending_operation_path(operation_id: str) -> Path:
    normalized = str(operation_id or "").strip().lower()
    if not re.fullmatch(r"[a-f0-9]{32}", normalized):
        raise ValueError("Agent 管理作業識別碼無效")
    return BACKUP_DIR / f".pending-{normalized}.json"


def _write_pending_operation(pending: Dict[str, Any]) -> None:
    _ensure_backup_dir()
    path = _pending_operation_path(pending["operation_id"])
    with path.open("x", encoding="utf-8", newline="\n") as handle:
        json.dump(pending, handle, ensure_ascii=False, separators=(",", ":"))
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


def _read_pending_operation(operation_id: str) -> Dict[str, Any]:
    path = _pending_operation_path(operation_id)
    if not path.is_file():
        raise ValueError("找不到待完成的 Agent 管理作業，請重新開始")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ValueError(f"無法讀取 Agent 管理作業：{exc}")
    if payload.get("operation_id") != str(operation_id).strip().lower():
        raise ValueError("Agent 管理作業內容不一致")
    return payload


def _display_path(path: Path) -> str:
    try:
        return str(path.relative_to(PROJECT_ROOT))
    except ValueError:
        return str(path)


def _save_agent_environment(
    main_address: str, private_key: str, network_config: Dict[str, Any]
) -> None:
    _write_env_values(
        {
            "POPDEX_ACCOUNT_ADDRESS": main_address,
            "POPDEX_AGENT_PRIVATE_KEY": private_key,
            "POPDEX_NETWORK": network_config["network"],
            "POPDEX_BASE_URL": network_config["base_url"],
            "POPDEX_RPC_URL": network_config["rpc_url"],
            "POPDEX_WS_URL": network_config["ws_url"],
            "POPDEX_CHAIN_ID": network_config["chain_id"],
        }
    )
